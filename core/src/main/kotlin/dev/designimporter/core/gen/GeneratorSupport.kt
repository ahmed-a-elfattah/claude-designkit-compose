package dev.designimporter.core.gen

import dev.designimporter.core.svg.PathData

enum class IconFormat { IMAGE_VECTOR, DRAWABLE }

data class GeneratorConfig(
    /** Package for the generated design system, e.g. "com.example.app.designsystem". */
    val packageName: String,
    /** Module namespace, used to import R for fonts and drawables. */
    val rPackage: String,
    val prefix: String = "App",
    val iconFormat: IconFormat = IconFormat.IMAGE_VECTOR,
    val kotlinSourceDir: String = "src/main/kotlin",
    val resDir: String = "src/main/res",
) {
    val packageDir get() = "$kotlinSourceDir/${packageName.replace('.', '/')}"
    val themeName get() = "${prefix}Theme"
}

/**
 * A file to write, path relative to the module root.
 * With [mergeBlock], [text] is only a block of entries merged into the (possibly user-owned) resources file at [path].
 */
class GeneratedFile(val path: String, val bytes: ByteArray, val isText: Boolean, val mergeBlock: Boolean = false) {
    val text: String get() = bytes.toString(Charsets.UTF_8)

    companion object {
        const val HEADER = "Generated by Claude DesignKit for Compose — do not edit"

        /** Headers written by earlier versions; files carrying them are still recognized as generated on re-import. */
        val LEGACY_HEADERS = listOf("Generated by Claude Design Importer")

        fun hasHeader(text: String) = text.contains(HEADER) || LEGACY_HEADERS.any { text.contains(it) }
        fun text(path: String, content: String) = GeneratedFile(path, content.toByteArray(Charsets.UTF_8), isText = true)
        fun binary(path: String, bytes: ByteArray) = GeneratedFile(path, bytes, isText = false)
        fun block(path: String, body: String) = GeneratedFile(path, body.toByteArray(Charsets.UTF_8), isText = true, mergeBlock = true)
    }
}

internal class KotlinFile(private val pkg: String) {
    private val imports = sortedSetOf<String>()
    private val body = StringBuilder()

    fun import(vararg names: String) = apply { imports += names }
    fun line(text: String = "") = apply { body.append(text).append('\n') }
    fun raw(text: String) = apply { body.append(text) }

    fun render(): String = buildString {
        append("// ${GeneratedFile.HEADER}\n\n")
        append("package $pkg\n\n")
        if (imports.isNotEmpty()) {
            imports.forEach { append("import ").append(it).append('\n') }
            append('\n')
        }
        append(body.toString().trimEnd()).append('\n')
    }
}

/** Single-line KDoc from a token's usage note. */
internal fun KotlinFile.doc(text: String?, indent: String = "    ") = apply {
    if (!text.isNullOrBlank()) line("$indent/** ${text.replace("*/", "*&#47;").replace(Regex("\\s+"), " ").trim()} */")
}

internal fun dp(v: Float) = "${PathData.num(v, 2)}.dp"
internal fun sp(v: Float) = if (v < 0) "(${PathData.num(v, 2)}).sp" else "${PathData.num(v, 2)}.sp"
internal fun flt(v: Float) = "${PathData.num(v, 3)}f"
internal fun colorLiteral(argb: Long) = "Color(0x%08X)".format(argb)
